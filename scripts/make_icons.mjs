// Turn the vendored Lucide SVGs (vendor/lucide/*.svg, byte-for-byte from
// lucide-static) into src/icons.js, which the page loads with a plain
// <script>: under file:// it cannot fetch the .svg files themselves.
// Run: npm run icons (also part of npm run build)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'vendor', 'lucide');
const icons = {};
let version = '';
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  let svg = fs.readFileSync(path.join(dir, file), 'utf8');
  version = (/lucide-static v([\d.]+)/.exec(svg) || [])[1] || version;
  // Drop the license comment (kept in the header below) and the fixed size,
  // so CSS sizes the icon; aria-hidden since the buttons carry labels.
  svg = svg.replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s*(width|height)="24"/g, '')
    .replace('<svg', '<svg aria-hidden="true"')
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .trim();
  icons[file.replace(/\.svg$/, '')] = svg;
}
const out = `/* Generated by scripts/make_icons.mjs from vendor/lucide/*.svg. Do not edit.
 * Lucide icons (lucide-static v${version}), ISC License, see vendor/lucide/LICENSE. */
window.KPM_ICONS = ${JSON.stringify(icons, null, 2)};
`;
fs.writeFileSync(path.join(root, 'src', 'icons.js'), out);
console.log(`wrote src/icons.js (${Object.keys(icons).join(', ')})`);
